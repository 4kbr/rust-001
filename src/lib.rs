pub fn say_hello(name: &str) -> String {
    format!("Hello {}", name)
}
pub fn say_hello_to_everyone() -> String {
    String::from("Hello All")
}
pub fn say_good_bye(name: &str) -> String {
    format!("Good Bye {}", name)
}
pub fn say_good_bye_to_everyone() -> String {
    String::from("Good Bye All")
}
 